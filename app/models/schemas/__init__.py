class TeacherProfileRequest(BaseModel):
    teacher_id: str
    full_name: str = Field(..., min_length=2, max_length=120)
    phone_number: str = Field(..., min_length=8, max_length=18)
    district: str = Field(..., min_length=2, max_length=120)
    subjects: List[str] = Field(..., min_length=1, max_length=8)
    bio: Optional[str] = Field(default=None, max_length=500)

    @field_validator("teacher_id")
    @classmethod
    def validate_teacher_id(cls, value: str) -> str:
        return sanitize_identifier(value)

    @field_validator("full_name", "district", "bio")
    @classmethod
    def sanitize_profile_text(cls, value: Optional[str]) -> Optional[str]:
        if value is None:
            return value
        return sanitize_text(value, max_length=500)

    @field_validator("subjects")
    @classmethod
    def sanitize_subjects(cls, values: List[str]) -> List[str]:
        return [sanitize_text(value, max_length=80) for value in values]

    @field_validator("phone_number")
    @classmethod
    def validate_phone_number(cls, value: str) -> str:
        normalized = value.strip()
        if not PHONE_RE.fullmatch(normalized):
            raise ValueError("Phone number must contain digits, spaces, hyphen, and optional +")
        return normalized

